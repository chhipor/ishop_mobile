class _ReportTile<T> extends StatelessWidget {
  const _ReportTile({
    required this.controller,
    required this.title,
    required this.icon,
    required this.kpi,
  });

  final AsyncController<T> controller;
  final String title;
  final IconData icon;
  final _Kpi Function(T report) kpi;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    return Card(
      child: Padding(
        padding: const EdgeInsets.all(14),
        child: ListenableBuilder(
          listenable: controller,
          builder: (context, _) {
            final data = controller.data;
            final error = controller.error;

            Widget header(String label) => Row(
              children: [
                Icon(icon, size: 18, color: theme.colorScheme.primary),
                const SizedBox(width: 6),
                Expanded(
                  child: Text(
                    label,
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                    style: theme.textTheme.labelMedium?.copyWith(
                      color: AppColors.inkMuted,
                    ),
                  ),
                ),
              ],
            );

            if (error != null && !controller.isLoading) {
              final info = ErrorInfo.from(error);
              return Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  header(title),
                  const Spacer(),
                  Text(
                    info.title,
                    maxLines: 2,
                    overflow: TextOverflow.ellipsis,
                    style: theme.textTheme.bodySmall?.copyWith(
                      color: AppColors.danger,
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                  if (info.retryable)
                    SizedBox(
                      height: 32,
                      child: TextButton(
                        style: TextButton.styleFrom(
                          padding: EdgeInsets.zero,
                          minimumSize: const Size(48, 32),
                        ),
                        onPressed: controller.load,
                        child: const Text('Retry'),
                      ),
                    ),
                ],
              );
            }

            if (data == null) {
              return Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  header(title),
                  const Spacer(),
                  const SkeletonBox(height: 22, width: 90),
                  const SizedBox(height: 8),
                  const SkeletonBox(height: 10, width: 60),
                ],
              );
            }

            final k = kpi(data);
            return Semantics(
              label:
                  '${k.label}: ${k.value}'
                  '${k.caption == null ? '' : ', ${k.caption}'}',
              excludeSemantics: true,
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  header(k.label),
                  const Spacer(),
                  FittedBox(
                    fit: BoxFit.scaleDown,
                    alignment: Alignment.centerLeft,
                    child: Text(
                      k.value,
                      maxLines: 1,
                      style: theme.textTheme.titleLarge?.copyWith(
                        fontWeight: FontWeight.w800,
                      ),
                    ),
                  ),
                  if (k.caption != null) ...[
                    const SizedBox(height: 2),
                    Text(
                      k.caption!,
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                      style: theme.textTheme.bodySmall?.copyWith(
                        color: AppColors.inkMuted,
                      ),
                    ),
                  ],
                ],
              ),
            );
          },
        ),
      ),
    );
  }
}

class _ListSection<T> extends StatelessWidget {
  const _ListSection({required this.controller, required this.builder});

  final AsyncController<T> controller;
  final Widget Function(T data) builder;

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: controller,
      builder: (context, _) {
        final data = controller.data;
        final error = controller.error;
        if (error != null && !controller.isLoading) {
          return ErrorView(
            error: error,
            onRetry: controller.load,
            compact: true,
          );
        }
        if (data == null) return const ListSkeleton();
        return builder(data);
      },
    );
  }
}

class _RecentOrdersCard extends StatelessWidget {
  const _RecentOrdersCard({required this.controller});

  final AsyncController<List<OrderResponse>> controller;

  @override
  Widget build(BuildContext context) {
    return SectionCard(
      title: 'Recent orders',
      subtitle: 'Latest 8, live',
      icon: Icons.receipt_long_outlined,
      child: _ListSection<List<OrderResponse>>(
        controller: controller,
        builder: (orders) {
          if (orders.isEmpty) {
            return const EmptyView(
              compact: true,
              icon: Icons.receipt_long_outlined,
              title: 'No orders yet',
            );
          }
          final recent = [...orders]
            ..sort((a, b) => b.orderDate.compareTo(a.orderDate));
          final shown = recent.take(8).toList();
          return Column(
            children: [
              for (var i = 0; i < shown.length; i++) ...[
                if (i > 0) const Divider(height: 1),
                _OrderRow(order: shown[i]),
              ],
            ],
          );
        },
      ),
    );
  }
}

